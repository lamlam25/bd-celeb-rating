// Generate dataset array for Excel export
export const generateDataset = () => {
  const rows = [];
  celebrities.forEach(celeb => {
    celeb.images.forEach((imgUrl, idx) => {
      rows.push({
        image_id: `${celeb.id}_${idx + 1}`,
        celebrity_id: celeb.id,
        celebrity_name: celeb.name,
        category: celeb.category,
        image_number: idx + 1,
        image_url: imgUrl,
      });
    });
  });
  return rows;
};
